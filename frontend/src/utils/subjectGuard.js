/**
 * 检查主题与所选学科是否明显矛盾。
 *
 * @param {string} topic 教学主题（如「细胞的结构」）
 * @param {string} current 当前所选学科（如「数学」）
 * @returns {{subject: string, matched: string[], message: string}|null}
 *          无明显矛盾时返回 null
 */
export function suggestSubject(topic, current) {
  const t = String(topic || '').trim()
  const cur = String(current || '').trim()
  if (!t || !cur) return null

  const hits = []
  for (const [subject, words] of Object.entries(SUBJECT_KEYWORDS)) {
    const matched = words.filter((w) => t.includes(w))
    if (matched.length) hits.push({ subject, matched })
  }
  if (!hits.length) return null

  // 当前学科自己就命中了 —— 说明选得对，不打扰
  if (hits.some((h) => h.subject === cur)) return null

  // 同时命中多门学科：本来就可能是跨学科课，系统不该替教师判
  if (hits.length > 1) return null

  const hit = hits[0]
  return {
    subject: hit.subject,
    matched: hit.matched,
    message: `主题「${t}」看起来是${hit.subject}内容（命中：${hit.matched.slice(0, 2).join('、')}），`
      + `但当前学科选的是${cur}。继续生成会得到一份${cur}化的课件，建议先确认学科。`,
  }
}
